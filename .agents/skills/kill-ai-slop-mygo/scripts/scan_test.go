package main_test

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

func TestScannerWorkflow(t *testing.T) {
	binary := filepath.Join(t.TempDir(), "scan")
	build := exec.Command("go", "build", "-o", binary, "scan.go")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build scanner: %v\n%s", err, output)
	}

	root := t.TempDir()
	files := map[string]string{
		"view.go": `package app
import native "github.com/egoist/mygo/ui"
func view(c *native.Context) {
    native.Column(c).
        Gradient(native.Hex("#6366f1"), native.Hex("#a855f7"), 90).
        Radius(24).
        Shadow(0, 2, 24, 0, native.RGB(0, 0, 0)).
        Padding(32).Children(func() {
            native.Text(c, "Supercharge your work 🚀").FontSize(32).Font("Georgia").OnClick(func(){})
            native.Badge(c, "New")
            native.Row(c).BorderWidth(0, 0, 0, 4).Background(native.Hex("#ffffff"))
        })
    // deslop-ignore-next-line M03 -- This preview is circular.
    native.Box(c).Radius(24).FontSize(40)
    native.Box(c).Radius(24) // deslop-ignore M03 -- Brush preview.
    native.Text(c, "deslop-ignore-file M05")
    // native.Text(c, "Seamless 🚀").FontSize(60)
    log("Seamless 🚀")
    other.Text(c, "Seamless 🚀").FontSize(60)
}
`,
		"theme.go": `package app
import "github.com/egoist/mygo/ui"
// deslop-ignore-file M02 -- Source color swatches.
func swatch(c *ui.Context) { ui.Box(c).Background(ui.RGB(1, 2, 3)).Radius(4) }
`,
		"generated.go": `// Code generated by catalogs. DO NOT EDIT.
package app
import "github.com/egoist/mygo/ui"
func generated(c *ui.Context) { ui.Text(c, "Seamless 🚀").FontSize(60) }
`,
		"view_test.go":     "invalid Go that must be skipped",
		"internal/core.go": "package core\nvar message = \"Seamless 🚀\"\n",
		"internal/locales/en.json": `{
  "supercharge": "Open a file",
  "welcome": "Seamless editing",
  "nested": {"message": "\u8d4b\u80fd", "icon": "\ud83d\ude80"}
}`,
		"translations/zh.json": `{"label": "打开文件"}`,
		"config.json":          `{"notCopy": "Seamless 🚀"}`,
		"README.md":            "Seamless 🚀",
		"vendor/bad.go":        "invalid Go",
		"testdata/bad.go":      "invalid Go",
		".agents/bad.go":       "invalid Go",
		"build/bad.go":         "invalid Go",
		"FEBuilderGBA/bad.go":  "invalid Go",
		"nested/.git":          "gitdir: elsewhere",
		"nested/bad.go":        "invalid Go",
	}
	for path, content := range files {
		path = filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	outside := filepath.Join(t.TempDir(), "outside.go")
	if err := os.WriteFile(outside, []byte("invalid Go"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(
		outside,
		filepath.Join(root, "linked.go"),
	); err != nil {
		t.Fatal(err)
	}

	type finding struct {
		Rule, File, Snippet string
		Line, Column        int
	}
	type report struct {
		Files    int
		Findings []finding
		Errors   []string
	}
	invoke := func(wantExit int, args ...string) ([]byte, string) {
		t.Helper()
		command := exec.Command(binary, args...)
		var stdout, stderr bytes.Buffer
		command.Stdout, command.Stderr = &stdout, &stderr
		err := command.Run()
		exit := 0
		if err != nil {
			failure, ok := err.(*exec.ExitError)
			if !ok {
				t.Fatal(err)
			}
			exit = failure.ExitCode()
		}
		if exit != wantExit {
			t.Fatalf(
				"scan %v: exit %d, want %d\n%s\n%s",
				args,
				exit,
				wantExit,
				stdout.String(),
				stderr.String(),
			)
		}
		return stdout.Bytes(), stderr.String()
	}
	decode := func(data []byte) report {
		t.Helper()
		var result report
		if err := json.Unmarshal(data, &result); err != nil {
			t.Fatalf("invalid report: %v\n%s", err, data)
		}
		return result
	}

	output, _ := invoke(0, "-root", root, "-json")
	result := decode(output)
	var locations []string
	for _, hit := range result.Findings {
		locations = append(
			locations,
			fmt.Sprintf("%s %s:%d", hit.Rule, hit.File, hit.Line),
		)
		if hit.Column < 1 || hit.Snippet == "" {
			t.Fatalf("missing source evidence: %+v", hit)
		}
	}
	want := []string{
		"M01 view.go:5", "M02 view.go:11", "M03 view.go:6", "M04 view.go:7",
		"M05 view.go:9", "M05 view.go:14", "M06 view.go:9", "M07 view.go:11",
		"M08 view.go:10", "M09 view.go:8", "M10 internal/locales/en.json:3",
		"M10 internal/locales/en.json:4", "M10 view.go:9",
		"M11 internal/locales/en.json:4", "M11 view.go:9", "M12 view.go:9",
	}
	if !reflect.DeepEqual(locations, want) || result.Files != 4 ||
		len(result.Errors) != 0 {
		t.Fatalf(
			"report mismatch: %+v\nlocations: %v\nwant: %v",
			result,
			locations,
			want,
		)
	}
	if result.Findings[0].Column != 9 || result.Findings[11].Snippet != "赋能" ||
		result.Findings[13].Snippet != "🚀" {
		t.Fatalf(
			"incorrect selector location or catalog decoding: %+v",
			result.Findings,
		)
	}
	repeated, _ := invoke(0, "-root", root, "-json")
	if !bytes.Equal(output, repeated) {
		t.Fatal("report order is unstable")
	}

	t.Run("filters and path boundaries", func(t *testing.T) {
		output, _ := invoke(
			0,
			"-root",
			root,
			"-json",
			"-only",
			"M03,M05,M10",
			"-skip",
			"M05",
			"-exclude",
			"internal",
			"-exclude",
			"view",
		)
		filtered := decode(output)
		if filtered.Files != 3 || len(filtered.Findings) != 2 ||
			filtered.Findings[0].Rule != "M03" ||
			filtered.Findings[1].Rule != "M10" {
			t.Fatalf("incorrect filters or exclusion boundary: %+v", filtered)
		}
		output, _ = invoke(
			0,
			"-root",
			root,
			"-json",
			"-exclude",
			"view.go",
			"-exclude",
			"internal",
		)
		if filtered = decode(
			output,
		); len(filtered.Findings) != 0 ||
			filtered.Files != 2 {
			t.Fatalf("file exclusion failed: %+v", filtered)
		}
	})

	t.Run("human report and catalog root", func(t *testing.T) {
		output, _ := invoke(0, "-root", root, "-only", "M01")
		if !strings.Contains(string(output), "M01 decorative gradient") ||
			!strings.Contains(string(output), "view.go:5:9") ||
			!strings.Contains(string(output), "1 candidates; 0 errors") {
			t.Fatalf("missing human evidence: %s", output)
		}
		output, _ = invoke(
			0,
			"-root",
			filepath.Join(root, "internal/locales"),
			"-json",
		)
		if catalog := decode(
			output,
		); catalog.Files != 1 ||
			len(catalog.Findings) != 3 {
			t.Fatalf("catalog root not scanned: %+v", catalog)
		}
	})

	t.Run("invalid invocation", func(t *testing.T) {
		for _, args := range [][]string{
			{"-only", "M99"},
			{"-skip", "M99"},
			{"-exclude", "../view.go"},
			{"-exclude", root},
			{"-unknown"},
			{root},
		} {
			_, stderr := invoke(2, args...)
			if stderr == "" {
				t.Fatalf("missing error for %v", args)
			}
		}
		output, _ := invoke(1, "-root", filepath.Join(root, "missing"), "-json")
		if missing := decode(output); len(missing.Errors) == 0 {
			t.Fatal("missing directory appeared clean")
		}
	})

	t.Run("incomplete scan is explicit", func(t *testing.T) {
		broken := map[string]string{
			"broken.go":                    "package app\nfunc broken(\n",
			"dot.go":                       "package app\nimport . \"github.com/egoist/mygo/ui\"\n",
			"internal/locales/broken.json": `{"message":`,
		}
		for path, content := range broken {
			if err := os.WriteFile(
				filepath.Join(root, path),
				[]byte(content),
				0o600,
			); err != nil {
				t.Fatal(err)
			}
		}
		output, _ := invoke(1, "-root", root, "-json")
		partial := decode(output)
		if len(partial.Errors) != 3 ||
			!reflect.DeepEqual(partial.Findings, result.Findings) {
			t.Fatalf("lost partial evidence or hid errors: %+v", partial)
		}
		for path := range broken {
			if err := os.Remove(filepath.Join(root, path)); err != nil {
				t.Fatal(err)
			}
		}
	})

	for path, original := range files {
		data, err := os.ReadFile(filepath.Join(root, path))
		if err != nil || string(data) != original {
			t.Fatalf("scanner changed %s: %v", path, err)
		}
	}
}
